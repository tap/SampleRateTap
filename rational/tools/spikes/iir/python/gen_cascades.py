"""IIR-0: the four-path designs as C++ and the counted cascades (I12).

    python3 gen_cascades.py       # after fourpath.py

Writes ../cpp/fourpath_designs.h (every placement's design: the one that met
-(A + 1 dB), else the best at the tie, flagged) and ../icount/cascades.inc,
the counted x4, x8 and x16 decimating cascades at `economy` in float and Q15
(scenarios 20 to 26 and 30 to 36 of workloads.cpp): the half-band cascade
(nonlinear, relaxed) against the same chain with one four-path stage in
place of a pair. Q15 runs every one-multiplier section with floor
truncation (no zero-input limit cycle for a > 0, fixed_point.cpp).
"""
import json
import pathlib

HERE = pathlib.Path(__file__).resolve().parent
OUT = HERE.parent / "outputs"


def arr(xs):
    return "{" + ", ".join(f"{x:.17g}" for x in xs) + "}"


def main():
    fp = json.loads((OUT / "fourpath.json").read_text())
    D_all = json.loads((OUT / "designs.json").read_text())
    h = ["// SPDX-License-Identifier: MIT", "// Copyright 2026 Timothy Place and the SampleRateTap contributors",
         "// Generated by rational/tools/spikes/iir/python/gen_cascades.py from outputs/fourpath.json.",
         "#pragma once", "", "#include <array>", "#include <span>", "", "namespace iir_spike {", "",
         "    struct fourpath_design {", "        const char* profile;", "        int D;", "        int sections;",
         "        std::array<std::span<const double>, 4> paths;", "        double stopband_db;",
         "        bool meets; // -(A + 1 dB) on the folding bands", "    };", ""]
    layouts = {}
    for key, e in fp.items():
        prof, dd = key.split("/")
        D = int(dd[1:])
        A = D_all["profiles"][prof]["A"]
        s = e["found_sections"] or max(int(k) for k in e["per_sections"])
        sb, layout, paths = e["per_sections"][str(s)]
        tag = f"{prof}_{D}"
        spans = []
        for k, pth in enumerate(paths):
            if pth:
                h.append(f"    inline constexpr double k_fp_{tag}_p{k}[] = {arr(pth)};")
                spans.append(f"k_fp_{tag}_p{k}")
            else:
                spans.append("std::span<const double>{}")
        h.append(f'    inline constexpr fourpath_design k_fp_{tag}{{"{prof}", {D}, {s}, {{{", ".join(spans)}}}, '
                 f'{sb:.2f}, {"true" if sb <= -(A + 1) else "false"}}};')
        layouts[tag] = layout
    h += ["", "} // namespace iir_spike", ""]
    (HERE.parent / "cpp" / "fourpath_designs.h").write_text("\n".join(h))

    # economy's relaxed nonlinear half-bands: d1 N9 <2,2>, d2 and d4 N5 <1,1>, d8 N3 <1,0>
    hb = {1: (2, 2), 2: (1, 1), 4: (1, 1), 8: (1, 0)}
    L = {D: layouts[f"economy_{D}"] for D in (1, 2, 4)}

    def chain(stages, fmt):
        """stages: list of ('hb', divisor) or ('fp', D) from the high rate down."""
        T = "float" if fmt == "float" else "std::int16_t"
        decl, init, body = [], [], []
        factors = [2 if k == "hb" else 4 for k, _ in stages]
        for i, (kind, v) in enumerate(stages):
            if kind == "hb":
                n0, n1 = hb[v]
                t = f"hb_dec<float, {n0}, {n1}>" if fmt == "float" else f"hb_dec_q15<{n0}, {n1}, true>"
                init.append(f"st.s{i}.init(nl(eco, {v}));")
            else:
                lay = ", ".join(str(x) for x in L[v])
                t = f"fp_dec<float, {lay}>" if fmt == "float" else f"fp_dec_q15<{lay}>"
                init.append(f"st.s{i}.init(k_fp_economy_{v});")
            decl.append(f"{t} s{i};")
        total = 1
        for f in factors:
            total *= f
        # buffers: after stage i the count is n * (product of the later factors)
        lines = []
        src = "in"
        for i in range(len(stages)):
            later = 1
            for f in factors[i + 1:]:
                later *= f
            dst = "out" if i == len(stages) - 1 else f"m{i}"
            if dst != "out":
                lines.append(f"{T} m{i}[k_frames * {later}];")
            lines.append(f"s{i}.process({src}, {dst}, n * {later});")
            src = dst
        body = " ".join(lines)
        return (f"    struct {{ {' '.join(decl)} [[gnu::noinline]] void process(const {T}* in, {T}* out, int n) noexcept "
                f"{{ {body} }} }} st;\n    " + " ".join(init) + f"\n    run_dec<{T}, decltype(st), {total}>(st);\n")

    plans = {
        0: [("hb", 2), ("hb", 1)],                     # x4 half-bands
        1: [("fp", 1)],                                # x4 four-path
        2: [("hb", 4), ("hb", 2), ("hb", 1)],          # x8 half-bands
        3: [("fp", 2), ("hb", 1)],                     # x8 four-path on top
        4: [("hb", 8), ("hb", 4), ("hb", 2), ("hb", 1)],  # x16 half-bands
        5: [("hb", 8), ("fp", 2), ("hb", 1)],          # x16 four-path in the middle
        6: [("fp", 4), ("hb", 2), ("hb", 1)],          # x16 four-path on top
    }
    inc = ["// Generated by rational/tools/spikes/iir/python/gen_cascades.py: workloads.cpp's scenarios 20-26",
           "// (float) and 30-36 (Q15), included inside main().", "#if 0"]
    for base, fmt in ((20, "float"), (30, "q15")):
        for k, stages in plans.items():
            inc.append(f"#elif IIR_SC == {base + k}")
            inc.append(chain(stages, fmt).rstrip("\n"))
    inc.append("#endif")
    (HERE.parent / "icount" / "cascades.inc").write_text("\n".join(inc) + "\n")
    print("layouts:", L)


if __name__ == "__main__":
    main()
