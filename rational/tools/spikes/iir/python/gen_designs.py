"""IIR-0: design every two-path half-band and guard band filter the spike
measures, and write them out.

    python3 gen_designs.py                # from this folder, in the notebook venv
    python3 gen_designs.py --header-only  # cpp/designs.h from outputs/designs.json

writes ../outputs/designs.json (every coefficient at full precision, with
its measured stopband) and ../cpp/designs.h (the same tables as constexpr
doubles for the C++ programs). The designs:
- nonlinear: the closed-form elliptic half-band (iir_design.nonlinear_design)
  at every profile and divisor 1, 2, 4, 8, the fewest coefficients meeting
  -(A + 1 dB) on the 16384-point grid;
- near-linear: the delay path w^-K and an order-N allpass path, by the
  iterated LP and its polish (iir_design.nearlinear_design), the lowest N
  meeting the same margin;
- the guard band filter's Chebyshev II at odd orders 3 to 11 per profile,
  its sections ordered by increasing pole radius with the L-inf gain rule.
"""
import json
import pathlib
import sys

import numpy as np

HERE = pathlib.Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import iir_design as d  # noqa: E402

OUT = HERE.parent / "outputs"
CPP = HERE.parent / "cpp"


def main():
    out = {"profiles": {}, "margin_db": d.MARGIN_DB, "grid": d.GRID}
    for name in d.PROFILE_ORDER:
        A, p = d.PROFILES[name]
        prof = {"A": A, "p": p, "nonlinear": {}, "near_linear": {}, "guard": {}}
        for div in d.DIVISORS:
            hb, sb = d.nonlinear_design(A, p, div)
            prof["nonlinear"][str(div)] = {
                "order": 2 * hb.multiplies + 1, "a0": hb.a0.tolist(), "a1": hb.a1.tolist(),
                "stopband_db": float(sb)}
            nl, sbl = d.nearlinear_design(A, p, div)
            prof["near_linear"][str(div)] = {
                "N": len(nl.den) - 1, "K": nl.K, "den": nl.den.tolist(),
                "sos": [list(s) for s in d.nearlinear_sos(nl.den)],
                "pole_radius": float(np.max(np.abs(np.roots(nl.den)))), "stopband_db": float(sbl)}
            print(f"{name} d{div}: nonlinear N{2 * hb.multiplies + 1} {sb:.1f} dB; "
                  f"near-linear N{len(nl.den) - 1} K{nl.K} {sbl:.1f} dB", flush=True)
        for order in (3, 5, 7, 9, 11):
            fs, zpk = d.cheby2_design(p, order, A)
            sos = d.cheby2_sos_ordered(zpk)
            prof["guard"][str(order)] = {"stop_edge": fs, "sos": sos.tolist(),
                                         "pole_radii": [float(max(abs(np.roots(s[3:])))) for s in sos]}
        out["profiles"][name] = prof
    OUT.mkdir(exist_ok=True)
    (OUT / "designs.json").write_text(json.dumps(out, indent=1) + "\n")
    write_header(out)


def arr(xs):
    return "{" + ", ".join(f"{x:.17g}" for x in xs) + "}"


def write_header(out):
    lines = [
        "// SPDX-License-Identifier: MIT",
        "// Copyright 2026 Timothy Place and the SampleRateTap contributors",
        "// Generated by rational/tools/spikes/iir/python/gen_designs.py: the IIR-0",
        "// spike's designs as doubles. Do not edit; regenerate.",
        "#pragma once",
        "",
        "// clang-format off: generated tables, kept one array per line",
        "#include <array>",
        "#include <cstddef>",
        "#include <span>",
        "",
        "namespace iir_spike {",
        "",
        "    struct nonlinear_design {",
        "        const char*             profile;",
        "        int                     divisor;",
        "        int                     order;",
        "        std::span<const double> a0;",
        "        std::span<const double> a1;",
        "        double                  stopband_db;",
        "    };",
        "    struct near_linear_design {",
        "        const char*             profile;",
        "        int                     divisor;",
        "        int                     N;",
        "        int                     K;",
        "        std::span<const double> den; // den[0] = 1",
        "        std::span<const double> sos; // (c1, c2) pairs, then c1 alone if N is odd",
        "        double                  stopband_db;",
        "    };",
        "    struct guard_design {",
        "        const char*             profile;",
        "        int                     order;",
        "        double                  stop_edge;",
        "        std::span<const double> sos; // b0 b1 b2 a0 a1 a2 per section",
        "    };",
        "",
    ]
    nl_rows, nr_rows, g_rows = [], [], []
    for name, prof in out["profiles"].items():
        for div, e in prof["nonlinear"].items():
            tag = f"{name}_{div}"
            spans = []
            for path in ("a0", "a1"):
                if e[path]:
                    lines.append(f"    inline constexpr double k_nl_{tag}_{path}[] = {arr(e[path])};")
                    spans.append(f"k_nl_{tag}_{path}")
                else:  # a path with no section is the bare delay (N3's path 1)
                    spans.append("std::span<const double>{}")
            nl_rows.append(f'        {{"{name}", {div}, {e["order"]}, {spans[0]}, {spans[1]}, {e["stopband_db"]:.3f}}},')
        for div, e in prof["near_linear"].items():
            tag = f"{name}_{div}"
            flat = [c for s in e["sos"] for c in s]
            lines.append(f"    inline constexpr double k_nr_{tag}_den[] = {arr(e['den'])};")
            lines.append(f"    inline constexpr double k_nr_{tag}_sos[] = {arr(flat)};")
            nr_rows.append(f'        {{"{name}", {div}, {e["N"]}, {e["K"]}, k_nr_{tag}_den, k_nr_{tag}_sos, '
                           f'{e["stopband_db"]:.3f}}},')
        for order, e in prof["guard"].items():
            tag = f"{name}_{order}"
            flat = [c for s in e["sos"] for c in s]
            lines.append(f"    inline constexpr double k_g_{tag}_sos[] = {arr(flat)};")
            g_rows.append(f'        {{"{name}", {order}, {e["stop_edge"]:.17g}, k_g_{tag}_sos}},')
    lines += ["", f"    inline constexpr nonlinear_design k_nonlinear[] = {{"] + nl_rows + ["    };"]
    lines += [f"    inline constexpr near_linear_design k_near_linear[] = {{"] + nr_rows + ["    };"]
    lines += [f"    inline constexpr guard_design k_guard[] = {{"] + g_rows + ["    };", "", "} // namespace iir_spike", "", "// clang-format on", ""]
    CPP.mkdir(exist_ok=True)
    (CPP / "designs.h").write_text("\n".join(lines))


if __name__ == "__main__":
    if "--header-only" in sys.argv:  # rewrite cpp/designs.h from outputs/designs.json
        write_header(json.loads((OUT / "designs.json").read_text()))
    else:
        main()
