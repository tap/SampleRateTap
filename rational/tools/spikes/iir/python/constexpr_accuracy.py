"""IIR-0 (IIR_PLAN I4): the constexpr half-band coefficients against an
mpmath leg at 60 digits, and against the same steps through libm (numpy).

    python3 constexpr_accuracy.py     # reads ../constexpr/expected_bits.txt

The constexpr bits are GCC 13's and Clang 18's (identical). The error is in
units of the last place (ulp) of each coefficient. It also evaluates a
reformulation of one step: e = (1 - k'^(1/2)) / (2 (1 + k'^(1/2))) loses
digits to cancellation when k is small (a wide transition, the relaxed
designs), and 1 - k'^(1/2) = k^2 / ((1 + k'^(1/2)) (1 + k')) with
k'^(1/2) = (1 - k^2)^(1/4) is the same quantity without it (algebra).
Writes ../outputs/constexpr_accuracy.md.
"""
import math
import pathlib
import struct
import sys

import mpmath
import numpy as np

HERE = pathlib.Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import iir_design as d  # noqa: E402

mpmath.mp.dps = 60


def ulp(x):
    return math.ulp(x)


def stable(ncoef, transition):
    """The same design with the cancellation-free e (double, numpy)."""
    order = 2 * ncoef + 1
    k = np.tan((1 - 2 * transition) * np.pi / 4) ** 2
    kk = np.sqrt(np.sqrt(1 - k * k))
    e = 0.5 * (k * k / ((1 + kk) * (1 + kk * kk))) / (1 + kk)
    e4 = e ** 4
    q = e * (1 + e4 * (2 + e4 * (15 + 150 * e4)))
    out = []
    for c in range(1, ncoef + 1):
        num = sum((-1) ** i * q ** (i * (i + 1)) * np.sin((2 * i + 1) * c * np.pi / order) for i in range(12))
        den = sum((-1) ** i * q ** (i * i) * np.cos(2 * i * c * np.pi / order) for i in range(1, 12))
        ww = num * np.sqrt(np.sqrt(q)) / (den + 0.5)
        w2 = ww * ww
        x = np.sqrt((1 - w2 * k) * (1 - w2 / k)) / (1 + w2)
        out.append((1 - x) / (1 + x))
    return out


def main():
    rows = []
    for line in (HERE.parent / "constexpr" / "expected_bits.txt").read_text().splitlines():
        if not line.startswith("halfband "):
            continue
        name, rest = line[len("halfband "):].split(":", 1)
        prof, div = name.split("/")
        bits = rest.split("|")[0].split()
        cx = [struct.unpack(">d", bytes.fromhex(b))[0] for b in bits]
        A, p = d.PROFILES[prof]
        tr = 0.5 - p / int(div)
        ref = d.halfband_coefficients(len(cx), mpmath.mpf(1) / 2 - mpmath.mpf(p) / int(div), m=mpmath.mp)
        lib = d.halfband_coefficients(len(cx), tr)
        st = stable(len(cx), tr)
        e_cx = max(abs(float((mpmath.mpf(c) - r) / ulp(c))) for c, r in zip(cx, ref))
        e_lib = max(abs(float((mpmath.mpf(c) - r) / ulp(c))) for c, r in zip(lib, ref))
        e_st = max(abs(float((mpmath.mpf(c) - r) / ulp(c))) for c, r in zip(st, ref))
        rows.append(f"| `{prof}` | {div} | {len(cx)} | {e_cx:.1f} | {e_st:.1f} | {e_lib:.1f} |")
    out = ["# IIR-0: constexpr half-band coefficients against mpmath (generated by python/constexpr_accuracy.py)", "",
           "Largest error per design in ulps of each coefficient, against the same formulas at 60 digits. "
           "`constexpr`: GCC 13 and Clang 18 (bit-identical, constexpr/expected_bits.txt), with the cancellation-free e. `libm, stable e`: the same steps through numpy's libm. `libm, prototype e`: libm with the prototype's e, which cancels "
           "when the transition is wide (the relaxed designs).", "",
           "| profile | divisor | coefficients | constexpr ulps | libm, stable e ulps | libm, prototype e ulps |", "|---|---:|---:|---:|---:|---:|"]
    out += rows
    (HERE.parent / "outputs" / "constexpr_accuracy.md").write_text("\n".join(out) + "\n")
    print("\n".join(out))


if __name__ == "__main__":
    main()
